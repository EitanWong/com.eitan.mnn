#!/usr/bin/env python3
"""Generate the offline Wenetspeech ppinyin lexicon. Requires pypinyin==0.55.0.

Run with --tokens pointing to the installed model's tokens.txt. No model downloads.
Only pronunciation data is embedded; no Python dependency exists in the Player.
"""
import argparse
import base64
import gzip
from pathlib import Path
import pypinyin
from pypinyin.constants import PINYIN_DICT, PHRASES_DICT
from pypinyin.contrib.tone_convert import to_initials, to_finals_tone


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tokens', required=True, type=Path)
    args = parser.parse_args()
    if pypinyin.__version__ != '0.55.0':
        parser.error('Use the pinned pypinyin==0.55.0 data release.')
    tokens = [line.rsplit(' ', 1)[0] for line in args.tokens.read_text().splitlines() if not line.startswith('#')]
    vocabulary = set(tokens)

    def phones(syllables):
        parts = []
        for syllable in syllables:
            # Matches official sherpa-mnn text2token(..., tokens_type="ppinyin").
            initial = to_initials(syllable, strict=False)
            final = to_finals_tone(syllable, strict=False)
            if not initial and not final:
                return None
            parts.extend(part for part in (initial, final) if part)
        return ' '.join(parts) if parts and all(part in vocabulary for part in parts) else None

    singles = {chr(code): value.split(',')[0] for code, value in PINYIN_DICT.items()}
    entries = {key: phones([value]) for key, value in singles.items()}
    for word, readings in PHRASES_DICT.items():
        syllables = [reading[0] for reading in readings]
        if len(word) > 1:
            entries[word] = phones(syllables)
    def han(char):
        return any(low <= ord(char) <= high for low, high in
                   ((0x3400, 0x9fff), (0xf900, 0xfaff), (0x20000, 0x323af)))

    entries = {key: value for key, value in entries.items() if value and all(map(han, key))}
    payload = ''.join(key + '\t' + value + '\n' for key, value in sorted(entries.items())).encode()
    encoded = base64.b64encode(gzip.compress(payload, mtime=0)).decode()
    chunks = [encoded[i:i+120] for i in range(0, len(encoded), 120)]
    package = Path(__file__).resolve().parents[2]
    output = package / 'Runtime/Core/AudioProcessing/KeywordSpotting/MNNKeywordText.Pronunciations.cs'
    output.write_text('// Generated by Tools~/Models/generate_kws_pronunciations.py; do not edit.\n'
                      '// pypinyin 0.55.0 pronunciation data, MIT; see Documentation~/KeywordPronunciationLicense.md.\n'
                      'namespace MNN.Unity\n{\n    public static partial class MNNKeywordText\n    {\n'
                      '        private static readonly string[] ModelTokens = "' + ' '.join(tokens) + '".Split(\' \');\n'
                      '        private static string PronunciationData() => string.Concat(new[]\n        {\n'
                      + ''.join('            "' + chunk + '",\n' for chunk in chunks)
                      + '        });\n    }\n}\n')
    print(f'{len(entries)} entries, {len(payload)} UTF-8 bytes, {len(encoded)} base64 bytes: {output}')


if __name__ == '__main__':
    main()
