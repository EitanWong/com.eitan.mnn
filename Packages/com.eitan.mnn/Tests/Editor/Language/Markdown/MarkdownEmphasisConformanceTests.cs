using NUnit.Framework;

namespace MNN.Unity.Tests
{
    // CommonMark 0.31.2 emphasis examples, https://spec.commonmark.org/0.31.2/.
    // Copyright (C) 2014-16 John MacFarlane. Derived from spec.txt examples.
    // SPDX-License-Identifier: CC-BY-SA-4.0
    // Adaptation: expected HTML formatting is converted to supported Unity rich-text tags.
    // See CommonMark.NOTICE.md for attribution and the upstream licensing notice:
    // https://github.com/commonmark/commonmark-spec/blob/0.31.2/LICENSE
    public sealed class MarkdownEmphasisConformanceTests
    {
        [TestCase("*foo bar*\n", "<i>foo bar</i>", 350)]
        [TestCase("a * foo bar*\n", "a * foo bar*", 351)]
        [TestCase("a*\"foo\"*\n", "a*\"foo\"*", 352)]
        [TestCase("* a *\n", "* a *", 353)]
        [TestCase("foo*bar*\n", "foo<i>bar</i>", 355)]
        [TestCase("5*6*78\n", "5<i>6</i>78", 356)]
        [TestCase("_foo bar_\n", "<i>foo bar</i>", 357)]
        [TestCase("_ foo bar_\n", "_ foo bar_", 358)]
        [TestCase("a_\"foo\"_\n", "a_\"foo\"_", 359)]
        [TestCase("foo_bar_\n", "foo_bar_", 360)]
        [TestCase("5_6_78\n", "5_6_78", 361)]
        [TestCase("пристаням_стремятся_\n", "пристаням_стремятся_", 362)]
        [TestCase("aa_\"bb\"_cc\n", "aa_\"bb\"_cc", 363)]
        [TestCase("foo-_(bar)_\n", "foo-<i>(bar)</i>", 364)]
        [TestCase("_foo*\n", "_foo*", 365)]
        [TestCase("*foo bar *\n", "*foo bar *", 366)]
        [TestCase("*foo bar\n*\n", "*foo bar\n*", 367)]
        [TestCase("*(*foo)\n", "*(*foo)", 368)]
        [TestCase("*(*foo*)*\n", "<i>(<i>foo</i>)</i>", 369)]
        [TestCase("*foo*bar\n", "<i>foo</i>bar", 370)]
        [TestCase("_foo bar _\n", "_foo bar _", 371)]
        [TestCase("_(_foo)\n", "_(_foo)", 372)]
        [TestCase("_(_foo_)_\n", "<i>(<i>foo</i>)</i>", 373)]
        [TestCase("_foo_bar\n", "_foo_bar", 374)]
        [TestCase("_пристаням_стремятся\n", "_пристаням_стремятся", 375)]
        [TestCase("_foo_bar_baz_\n", "<i>foo_bar_baz</i>", 376)]
        [TestCase("_(bar)_.\n", "<i>(bar)</i>.", 377)]
        [TestCase("**foo bar**\n", "<b>foo bar</b>", 378)]
        [TestCase("** foo bar**\n", "** foo bar**", 379)]
        [TestCase("a**\"foo\"**\n", "a**\"foo\"**", 380)]
        [TestCase("foo**bar**\n", "foo<b>bar</b>", 381)]
        [TestCase("__foo bar__\n", "<b>foo bar</b>", 382)]
        [TestCase("__ foo bar__\n", "__ foo bar__", 383)]
        [TestCase("__\nfoo bar__\n", "__\nfoo bar__", 384)]
        [TestCase("a__\"foo\"__\n", "a__\"foo\"__", 385)]
        [TestCase("foo__bar__\n", "foo__bar__", 386)]
        [TestCase("5__6__78\n", "5__6__78", 387)]
        [TestCase("пристаням__стремятся__\n", "пристаням__стремятся__", 388)]
        [TestCase("__foo, __bar__, baz__\n", "<b>foo, <b>bar</b>, baz</b>", 389)]
        [TestCase("foo-__(bar)__\n", "foo-<b>(bar)</b>", 390)]
        [TestCase("**foo bar **\n", "**foo bar **", 391)]
        [TestCase("**(**foo)\n", "**(**foo)", 392)]
        [TestCase("*(**foo**)*\n", "<i>(<b>foo</b>)</i>", 393)]
        [TestCase("**Gomphocarpus (*Gomphocarpus physocarpus*, syn.\n*Asclepias physocarpa*)**\n", "<b>Gomphocarpus (<i>Gomphocarpus physocarpus</i>, syn.\n<i>Asclepias physocarpa</i>)</b>", 394)]
        [TestCase("**foo \"*bar*\" foo**\n", "<b>foo \"<i>bar</i>\" foo</b>", 395)]
        [TestCase("**foo**bar\n", "<b>foo</b>bar", 396)]
        [TestCase("__foo bar __\n", "__foo bar __", 397)]
        [TestCase("__(__foo)\n", "__(__foo)", 398)]
        [TestCase("_(__foo__)_\n", "<i>(<b>foo</b>)</i>", 399)]
        [TestCase("__foo__bar\n", "__foo__bar", 400)]
        [TestCase("__пристаням__стремятся\n", "__пристаням__стремятся", 401)]
        [TestCase("__foo__bar__baz__\n", "<b>foo__bar__baz</b>", 402)]
        [TestCase("__(bar)__.\n", "<b>(bar)</b>.", 403)]
        [TestCase("*foo\nbar*\n", "<i>foo\nbar</i>", 405)]
        [TestCase("_foo __bar__ baz_\n", "<i>foo <b>bar</b> baz</i>", 406)]
        [TestCase("_foo _bar_ baz_\n", "<i>foo <i>bar</i> baz</i>", 407)]
        [TestCase("__foo_ bar_\n", "<i><i>foo</i> bar</i>", 408)]
        [TestCase("*foo *bar**\n", "<i>foo <i>bar</i></i>", 409)]
        [TestCase("*foo **bar** baz*\n", "<i>foo <b>bar</b> baz</i>", 410)]
        [TestCase("*foo**bar**baz*\n", "<i>foo<b>bar</b>baz</i>", 411)]
        [TestCase("*foo**bar*\n", "<i>foo**bar</i>", 412)]
        [TestCase("***foo** bar*\n", "<i><b>foo</b> bar</i>", 413)]
        [TestCase("*foo **bar***\n", "<i>foo <b>bar</b></i>", 414)]
        [TestCase("*foo**bar***\n", "<i>foo<b>bar</b></i>", 415)]
        [TestCase("foo***bar***baz\n", "foo<i><b>bar</b></i>baz", 416)]
        [TestCase("foo******bar*********baz\n", "foo<b><b><b>bar</b></b></b>***baz", 417)]
        [TestCase("*foo **bar *baz* bim** bop*\n", "<i>foo <b>bar <i>baz</i> bim</b> bop</i>", 418)]
        [TestCase("** is not an empty emphasis\n", "** is not an empty emphasis", 420)]
        [TestCase("**** is not an empty strong emphasis\n", "**** is not an empty strong emphasis", 421)]
        [TestCase("**foo\nbar**\n", "<b>foo\nbar</b>", 423)]
        [TestCase("__foo _bar_ baz__\n", "<b>foo <i>bar</i> baz</b>", 424)]
        [TestCase("__foo __bar__ baz__\n", "<b>foo <b>bar</b> baz</b>", 425)]
        [TestCase("____foo__ bar__\n", "<b><b>foo</b> bar</b>", 426)]
        [TestCase("**foo **bar****\n", "<b>foo <b>bar</b></b>", 427)]
        [TestCase("**foo *bar* baz**\n", "<b>foo <i>bar</i> baz</b>", 428)]
        [TestCase("**foo*bar*baz**\n", "<b>foo<i>bar</i>baz</b>", 429)]
        [TestCase("***foo* bar**\n", "<b><i>foo</i> bar</b>", 430)]
        [TestCase("**foo *bar***\n", "<b>foo <i>bar</i></b>", 431)]
        [TestCase("**foo *bar **baz**\nbim* bop**\n", "<b>foo <i>bar <b>baz</b>\nbim</i> bop</b>", 432)]
        [TestCase("__ is not an empty emphasis\n", "__ is not an empty emphasis", 434)]
        [TestCase("____ is not an empty strong emphasis\n", "____ is not an empty strong emphasis", 435)]
        [TestCase("foo ***\n", "foo ***", 436)]
        [TestCase("foo *\\**\n", "foo <i>*</i>", 437)]
        [TestCase("foo *_*\n", "foo <i>_</i>", 438)]
        [TestCase("foo *****\n", "foo *****", 439)]
        [TestCase("foo **\\***\n", "foo <b>*</b>", 440)]
        [TestCase("foo **_**\n", "foo <b>_</b>", 441)]
        [TestCase("**foo*\n", "*<i>foo</i>", 442)]
        [TestCase("*foo**\n", "<i>foo</i>*", 443)]
        [TestCase("***foo**\n", "*<b>foo</b>", 444)]
        [TestCase("****foo*\n", "***<i>foo</i>", 445)]
        [TestCase("**foo***\n", "<b>foo</b>*", 446)]
        [TestCase("*foo****\n", "<i>foo</i>***", 447)]
        [TestCase("foo ___\n", "foo ___", 448)]
        [TestCase("foo _\\__\n", "foo <i>_</i>", 449)]
        [TestCase("foo _*_\n", "foo <i>*</i>", 450)]
        [TestCase("foo _____\n", "foo _____", 451)]
        [TestCase("foo __\\___\n", "foo <b>_</b>", 452)]
        [TestCase("foo __*__\n", "foo <b>*</b>", 453)]
        [TestCase("__foo_\n", "_<i>foo</i>", 454)]
        [TestCase("_foo__\n", "<i>foo</i>_", 455)]
        [TestCase("___foo__\n", "_<b>foo</b>", 456)]
        [TestCase("____foo_\n", "___<i>foo</i>", 457)]
        [TestCase("__foo___\n", "<b>foo</b>_", 458)]
        [TestCase("_foo____\n", "<i>foo</i>___", 459)]
        [TestCase("**foo**\n", "<b>foo</b>", 460)]
        [TestCase("*_foo_*\n", "<i><i>foo</i></i>", 461)]
        [TestCase("__foo__\n", "<b>foo</b>", 462)]
        [TestCase("_*foo*_\n", "<i><i>foo</i></i>", 463)]
        [TestCase("****foo****\n", "<b><b>foo</b></b>", 464)]
        [TestCase("____foo____\n", "<b><b>foo</b></b>", 465)]
        [TestCase("******foo******\n", "<b><b><b>foo</b></b></b>", 466)]
        [TestCase("***foo***\n", "<i><b>foo</b></i>", 467)]
        [TestCase("_____foo_____\n", "<i><b><b>foo</b></b></i>", 468)]
        [TestCase("*foo _bar* baz_\n", "<i>foo _bar</i> baz_", 469)]
        [TestCase("*foo __bar *baz bim__ bam*\n", "<i>foo <b>bar *baz bim</b> bam</i>", 470)]
        [TestCase("**foo **bar baz**\n", "**foo <b>bar baz</b>", 471)]
        [TestCase("*foo *bar baz*\n", "*foo <i>bar baz</i>", 472)]
        [TestCase("*a `*`*\n", "<i>a <color=#C9D4EA>*</color></i>", 478)]
        [TestCase("_a `_`_\n", "<i>a <color=#C9D4EA>_</color></i>", 479)]
        public void MatchesSupportedCommonMarkEmphasisExamples(string source, string expected, int example)
        {
            Assert.AreEqual(expected, MNNMarkdownRenderer.ToRichText(source), "CommonMark example " + example);
        }
    }
}
